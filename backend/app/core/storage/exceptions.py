class StorageError(Exception):
    """Base class for storage-related errors."""
    pass


class ObjectNotFoundError(StorageError):
    """Raised when the requested object does not exist in storage."""
    pass


class InvalidPathError(StorageError):
    """Raised when the provided storage path is invalid or insecure."""
    pass


class AvatarStorageError(StorageError):
    """Sanitized avatar-storage failure with optional internal cleanup ownership."""

    MESSAGES = {
        "write_failed": "Avatar file could not be written",
        "publication_failed": "Avatar file could not be published",
        "durability_failed": "Avatar file durability could not be confirmed",
        "too_large": "Stored avatar exceeds the permitted size",
        "delete_failed": "Avatar file could not be deleted",
        "unsafe_path": "Avatar storage path is unsafe",
        "immutable_exists": "Avatar version already exists",
        "missing": "Avatar file is unavailable",
        "read_failed": "Avatar file could not be read",
    }

    def __init__(self, outcome: str, *, storage_key: str | None = None):
        self.outcome = outcome
        self.storage_key = storage_key
        super().__init__(self.MESSAGES.get(outcome, "Avatar storage operation failed"))


class StickerStorageError(StorageError):
    """Sanitized sticker-storage failure; storage_key is generated internally."""

    MESSAGES = {
        "write_failed": "Sticker file could not be written",
        "publication_failed": "Sticker file could not be published",
        "durability_failed": "Sticker file durability could not be confirmed",
        "too_large": "Stored sticker exceeds the permitted size",
        "delete_failed": "Sticker file could not be deleted",
        "unsafe_path": "Sticker storage path is unsafe",
        "immutable_exists": "Sticker version already exists",
        "missing": "Sticker file is unavailable",
        "read_failed": "Sticker file could not be read",
    }

    def __init__(self, outcome: str, *, storage_key: str | None = None):
        self.outcome = outcome
        # A key is returned only when generated by this process and may be used
        # by a transaction coordinator for narrow, ownership-validated cleanup.
        self.storage_key = storage_key
        super().__init__(self.MESSAGES.get(outcome, "Sticker storage operation failed"))


